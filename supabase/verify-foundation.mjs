// Integration checks against Supabase PostgreSQL. All test data is rolled back.
// Run: node supabase/verify-foundation.mjs
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';

const require = createRequire(new URL('../lib/db/package.json', import.meta.url));
const { Client } = require('pg');
const connection = new URL(process.env.SUPABASE_DATABASE_URL);
const project = new URL(process.env.VITE_SUPABASE_URL).hostname.split('.')[0];
assert(connection.hostname === `db.${project}.supabase.co`
  || decodeURIComponent(connection.username).endsWith(`.${project}`), 'Project mismatch');
connection.searchParams.delete('sslmode');
const client = new Client({
  connectionString: connection.toString(),
  ssl: { rejectUnauthorized: true, ca: readFileSync(new URL('./certs/supabase-root-2021.crt', import.meta.url), 'utf8') },
  connectionTimeoutMillis: 15000,
});
const checks = [];
const [a, b, c, unverified] = Array.from({ length: 4 }, () => randomUUID());
const post = randomUUID();
const conversation = randomUUID();
const query = (sql, params = []) => client.query(sql, params);
async function asUser(id) {
  await query('reset role');
  await query("select set_config('request.jwt.claim.sub',$1,true)", [id]);
  await query('set local role authenticated');
}
async function denied(label, sql, params, code = '42501') {
  await query('savepoint denied_check');
  try {
    await query(sql, params);
    assert.fail(`${label}: unexpectedly allowed`);
  } catch (error) {
    assert.equal(error.code, code, label);
    checks.push(label);
  } finally {
    await query('rollback to savepoint denied_check');
  }
}
try {
  await client.connect();
  await query('begin');
  await query("set local statement_timeout = '15s'");
  const schema = await query("select tablename, rowsecurity from pg_tables where schemaname='public'");
  const expected = ['profiles','profile_private','posts','post_media','listings','likes','comments','follows',
    'saved_posts','conversations','messages','conversation_reads','requests','notifications','reviews','reports'];
  for (const name of expected) assert(schema.rows.some(r => r.tablename === name && r.rowsecurity), `${name}: missing RLS`);
  checks.push('All 16 tables have RLS enabled');
  // Internal fixtures bypass Auth API only inside this rollback transaction.
  // This tests database authorization, NOT registration or email delivery.
  for (const id of [a, b, c, unverified]) {
    await query('insert into auth.users(id,email_confirmed_at) values($1,$2)', [id, id === unverified ? null : new Date()]);
    if (id !== unverified) {
      await query(`insert into public.profiles(id,username,full_name,college,campus,department,year_of_study)
        values($1,$2,'RLS Test','Test College','Test Campus','Test Department',1)`, [id, `test_${id.replaceAll('-','').slice(0,20)}`]);
    }
  }
  await asUser(a);
  await query("insert into public.posts(author_id,type,body) values($1,'normal','RLS fixture')", [a]);
  // Obtain only the row generated by this test.
  const own = (await query("select id from public.posts where author_id=$1", [a])).rows[0].id;
  checks.push('Verified user can create own post');
  const listingPost = (await query("insert into public.posts(type,body) values('sell','Listing fixture') returning id")).rows[0].id;
  const listing = (await query(`insert into public.listings(post_id,title,category,campus,price)
    values($1,'Audit listing','Electronics','Test Campus',100) returning id`,[listingPost])).rows[0].id;
  assert.equal((await query("update public.listings set title='Updated audit listing',price=150 where id=$1 returning id",[listing])).rowCount,1);
  assert.equal((await query('select price from public.listings where id=$1',[listing])).rows[0].price,'150.00');
  checks.push('Owner can create, read and edit database listing');
  await asUser(b);
  assert.equal((await query("select id from public.listings where title ilike $1",['%Updated audit%'])).rowCount,1);
  assert.equal((await query("update public.listings set price=1 where id=$1 returning id",[listing])).rowCount,0);
  assert.equal((await query("delete from public.listings where id=$1 returning id",[listing])).rowCount,0);
  await query('insert into public.saved_posts(user_id,post_id) values($1,$2)',[b,listingPost]);
  assert.equal((await query('select post_id from public.saved_posts where user_id=$1 and post_id=$2',[b,listingPost])).rowCount,1);
  assert.equal((await query('delete from public.saved_posts where user_id=$1 and post_id=$2 returning post_id',[b,listingPost])).rowCount,1);
  checks.push('Database listing search and favorite/unfavorite work');
  checks.push('Non-owner cannot update or delete database listing');
  await asUser(a);
  assert.equal((await query('delete from public.posts where id=$1 returning id',[listingPost])).rowCount,1);
  assert.equal((await query('select id from public.listings where id=$1',[listing])).rowCount,0);
  checks.push('Owner deletion cascades from post to listing');
  await denied('Cannot forge post author', "insert into public.posts(author_id,type,body) values($1,'normal','bad')", [b]);
  await denied('Cannot forge server timestamp', "insert into public.posts(type,body,created_at) values('normal','bad',now())", []);
  await asUser(b);
  assert.equal((await query("update public.posts set body='bad' where id=$1 returning id", [own])).rowCount, 0);
  assert.equal((await query('delete from public.posts where id=$1 returning id', [own])).rowCount, 0);
  checks.push('Other users cannot edit or delete posts');
  await denied('Duplicate username rejected', 'update public.profiles set username=(select username from public.profiles where id=$1) where id=$2', [a,b], '23505');
  await asUser(a);
  await query("insert into public.profile_private(user_id,contact_details) values($1,'{\"test\":true}')", [a]);
  await query("insert into public.saved_posts(user_id,post_id) values($1,$2)", [a,own]);
  await asUser(b);
  assert.equal((await query('select * from public.profile_private where user_id=$1',[a])).rowCount,0);
  assert.equal((await query('select * from public.saved_posts where user_id=$1',[a])).rowCount,0);
  checks.push('Private contacts and saved posts are owner-only');
  await asUser(a);
  const avatarPath = `${a}/${randomUUID()}.jpg`;
  await query("insert into storage.objects(bucket_id,name) values('secondsignal-avatars',$1)", [avatarPath]);
  await asUser(b);
  assert.equal((await query("select id from storage.objects where bucket_id='secondsignal-avatars' and name=$1", [avatarPath])).rowCount,0);
  await denied('Cannot expose another user private avatar', 'update public.profiles set avatar_path=$1 where id=$2', [avatarPath,b], '23514');
  await denied('Cannot upload into another user folder', "insert into storage.objects(bucket_id,name) values('secondsignal-media',$1)", [`${a}/${randomUUID()}.jpg`]);
  checks.push('Unattached media remains private to uploader');
  await query('reset role');
  await query('insert into public.conversations(id,participant_a,participant_b) values($1,$2,$3)', [conversation,...[a,b].sort()]);
  await asUser(a);
  await query("insert into public.messages(conversation_id,sender_id,body) values($1,$2,'Private fixture')",[conversation,a]);
  await asUser(b);
  assert.equal((await query('select * from public.messages where conversation_id=$1',[conversation])).rowCount,1);
  checks.push('Conversation participant can read messages');
  await asUser(c);
  assert.equal((await query('select * from public.messages where conversation_id=$1',[conversation])).rowCount,0);
  assert.equal((await query('select * from public.conversations where id=$1',[conversation])).rowCount,0);
  await denied('Outsider cannot send a message', "insert into public.messages(conversation_id,sender_id,body) values($1,$2,'bad')",[conversation,c]);
  checks.push('Outsider cannot read conversation or messages');
  await asUser(a);
  await denied('Cannot forge notifications', "insert into public.notifications(recipient_id,type) values($1,'bad')",[b]);
  await denied('Cannot directly force request completion', "update public.requests set status='completed'",[]);
  await denied('Foreign keys reject nonexistent post', 'insert into public.likes(user_id,post_id) values($1,$2)',[a,post],'23503');
  await asUser(unverified);
  assert.equal((await query('select * from public.profiles')).rowCount,0);
  await denied('Unverified user cannot create profile', `insert into public.profiles(id,username,full_name,college,campus,department,year_of_study)
    values($1,'unverified_test','Test','Test','Test','Test',1)`,[unverified]);
  await query('reset role');
  await query('set local role anon');
  await denied('Anonymous access denied', 'select * from public.profiles',[]);
  await query('reset role');
  const buckets = (await query("select id,public,file_size_limit from storage.buckets where id in ('secondsignal-media','secondsignal-avatars')")).rows;
  assert.equal(buckets.length,2);
  assert(buckets.every(r => r.public === false && Number(r.file_size_limit) > 0));
  checks.push('Both upload buckets are private and size-limited');
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} catch (error) {
  // Deliberately do not log connection objects, passwords or database error detail.
  console.error(JSON.stringify({ failed: true, code: error.code ?? null, assertion: error.name === 'AssertionError' ? error.message : undefined }));
  process.exitCode = 1;
} finally {
  await client.query('rollback').catch(() => {});
  await client.end().catch(() => {});
  console.log('Test transaction rolled back; no test records retained.');
}
